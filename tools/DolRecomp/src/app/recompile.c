#define CHUNK_INSTRUCTIONS 4096u
#define HEADER_NAME "ppc_recomp.h"

static u32 host_threads(void) {
#ifdef _WIN32
    SYSTEM_INFO info;
    GetSystemInfo(&info);
    return info.dwNumberOfProcessors ? (u32)info.dwNumberOfProcessors : 1u;
#else
    const long count = sysconf(_SC_NPROCESSORS_ONLN);
    return count > 0 ? (u32)count : 1u;
#endif
}

static int compare_u32(const void* left, const void* right) {
    const u32 a = *(const u32*)left, b = *(const u32*)right;
    return a < b ? -1 : a > b;
}

static void add_entry_target(u32* targets, u32* count, const LoadedCodeSection* sections,
                             u32 section_count, u32 address) {
    for (u32 i = 0; i < section_count; i++) {
        if (address - sections[i].address < sections[i].size && (address & 3u) == 0) {
            targets[(*count)++] = address;
            return;
        }
    }
}

// Every address code can enter a function at from outside it, for the sparse
// entry switches: the program entry, every direct branch target, and every
// DOL data word that points at an instruction (vtables, jump tables,
// callbacks). Code pointers built in registers that none of these cover are
// found at run time by the runtime stepping the instruction.
static u32* collect_entry_targets(const DOLFile* dol, const LoadedCodeSection* sections,
                                  u32 section_count, u32* result_count) {
    size_t capacity = 1u;
    for (u32 i = 0; i < section_count; i++)
        capacity += sections[i].size / 4u;
    for (int i = 0; i < DOL_NUM_DATA; i++)
        capacity += dol->header.data_sizes[i] / 4u;
    u32* targets = (u32*)malloc(capacity * sizeof(*targets));
    if (!targets)
        return NULL;
    u32 count = 0;
    add_entry_target(targets, &count, sections, section_count, dol->header.entry_point);
    for (u32 s = 0; s < section_count; s++) {
        const LoadedCodeSection* section = &sections[s];
        for (u32 offset = 0; offset + 4u <= section->size; offset += 4u) {
            // Text words are not scanned as pointers: every lwz r0-r3 reads as one.
            const PPCInst inst = ppc_decode(read_be32(section->data + offset), section->address + offset);
            if (inst.op == PPC_OP_B || inst.op == PPC_OP_BC)
                add_entry_target(targets, &count, sections, section_count, inst.branch_target);
        }
    }
    for (int i = 0; i < DOL_NUM_DATA; i++) {
        const u8* data = dol->header.data_sizes[i] ? dol_get_data_section(dol, i) : NULL;
        for (u32 offset = 0; data && offset + 4u <= dol->header.data_sizes[i]; offset += 4u)
            add_entry_target(targets, &count, sections, section_count, read_be32(data + offset));
    }
    qsort(targets, count, sizeof(*targets), compare_u32);
    u32 unique = 0;
    for (u32 i = 0; i < count; i++) {
        if (!unique || targets[i] != targets[unique - 1u])
            targets[unique++] = targets[i];
    }
    *result_count = unique;
    return targets;
}

static u64 fnv1a64(const u8* data, u32 size) {
    u64 hash = 0xCBF29CE484222325ull;
    for (u32 i = 0; i < size; i++) {
        hash ^= data[i];
        hash *= 0x100000001B3ull;
    }
    return hash;
}

static const u8* section_bytes(const LoadedCodeSection* sections, u32 count, u32 start, u32 end) {
    for (u32 i = 0; i < count; i++) {
        if (start - sections[i].address < sections[i].size && end - sections[i].address <= sections[i].size)
            return sections[i].data + (start - sections[i].address);
    }
    return NULL;
}

// The runtime's view of the module: what the dispatcher covers, and per chunk
// its range and the hash of the text it was built from.
static int write_tables(const char* path, const LoadedCodeSection* sections, u32 section_count,
                        const FunctionList* chunks, const u32* order) {
    FILE* out = fopen(path, "w");
    if (!out) {
        fprintf(stderr, "error: can't open output '%s'\n", path);
        return 0;
    }
    fprintf(out, "// Generated by DolRecomp.\n");
    fprintf(out, "static const GuestRange s_code_ranges[] = {\n");
    for (u32 i = 0; i < section_count; i++) {
        const LoadedCodeSection* section = &sections[order[i]];
        fprintf(out, "    {0x%08Xu, 0x%08Xu},\n", section->address, section->address + section->size);
    }
    fprintf(out, "};\n");
    fprintf(out, "static const GuestRange s_chunk_ranges[] = {\n");
    for (u32 i = 0; i < chunks->count; i++)
        fprintf(out, "    {0x%08Xu, 0x%08Xu},\n", chunks->ranges[i].start, chunks->ranges[i].end);
    fprintf(out, "};\n");
    fprintf(out, "static const u64 s_chunk_hashes[] = {\n");
    for (u32 i = 0; i < chunks->count; i++) {
        const FunctionRange* chunk = &chunks->ranges[i];
        const u8* bytes = section_bytes(sections, section_count, chunk->start, chunk->end);
        fprintf(out, "    0x%016llXull,\n",
                (unsigned long long)(bytes ? fnv1a64(bytes, chunk->end - chunk->start) : 0));
    }
    fprintf(out, "};\n");
    const int ok = fclose(out) == 0;
    if (!ok)
        fprintf(stderr, "error: can't write '%s'\n", path);
    return ok;
}

// Fixed-count sources that include the chunks round-robin, so the build can
// name its sources before the recompiler has run.
static int write_shards(const char* out_dir, u32 shards, char (*chunk_names)[128], u32 chunk_count) {
    for (u32 shard = 0; shard < shards; shard++) {
        char name[64], path[1200];
        snprintf(name, sizeof(name), "ppc_recomp.%u.c", shard);
        if (!join_path(path, sizeof(path), out_dir, name))
            return 0;
        FILE* out = fopen(path, "w");
        if (!out) {
            fprintf(stderr, "error: can't open output '%s'\n", path);
            return 0;
        }
        fprintf(out, "// Generated by DolRecomp.\n#include \"" HEADER_NAME "\"\n");
        for (u32 chunk = shard; chunk < chunk_count; chunk += shards)
            fprintf(out, "#include \"chunks/%s\"\n", chunk_names[chunk]);
        if (fclose(out) != 0) {
            fprintf(stderr, "error: can't write '%s'\n", path);
            return 0;
        }
    }
    return 1;
}

static const LoadedCodeSection* s_sort_sections;

static int compare_section_index(const void* left, const void* right) {
    const u32 a = s_sort_sections[*(const u32*)left].address;
    const u32 b = s_sort_sections[*(const u32*)right].address;
    return a < b ? -1 : a > b;
}

static int emit_sections(const LoadedCodeSection* sections, u32 section_count, const char* out_dir,
                         u32 entry_point, u32 shards) {
    char header_path[1200], chunks_dir[1200], tables_path[1200];
    if (!join_path(header_path, sizeof(header_path), out_dir, HEADER_NAME) ||
        !join_path(chunks_dir, sizeof(chunks_dir), out_dir, "chunks") ||
        !join_path(tables_path, sizeof(tables_path), out_dir, "ppc_tables.inc") ||
        !make_dir_tree(chunks_dir)) {
        fprintf(stderr, "error: output path is too long or can't be created\n");
        return 0;
    }
    FILE* header = fopen(header_path, "w");
    if (!header) {
        fprintf(stderr, "error: can't open output '%s'\n", header_path);
        return 0;
    }
    emit_header_for_cpu(header, DOLRECOMP_CPU_BROADWAY);
    fprintf(header, "\n// Function entry points\n");

    const u32 jobs = host_threads();
    FunctionList funcs = {0};
    char (*chunk_names)[128] = NULL;
    u32 chunk_count = 0;
    int ok = 0;

    for (u32 s = 0; s < section_count; s++) {
        const LoadedCodeSection* section = &sections[s];
        const u32 num_insts = section->size / 4u;
        printf("decoding %s[%u]: %u instructions at 0x%08X\n", section->label, section->index,
               num_insts, section->address);

        PPCInst* insts = (PPCInst*)malloc((size_t)num_insts * sizeof(PPCInst));
        const u32 job_count = (num_insts + CHUNK_INSTRUCTIONS - 1u) / CHUNK_INSTRUCTIONS;
        ChunkJob* chunk_jobs = (ChunkJob*)calloc(job_count ? job_count : 1u, sizeof(ChunkJob));
        char (*names)[128] = (char (*)[128])realloc(chunk_names, (size_t)(chunk_count + job_count) * 128u);
        if (names)
            chunk_names = names;
        if (!insts || !chunk_jobs || !names) {
            fprintf(stderr, "error: out of memory\n");
            free(insts);
            free(chunk_jobs);
            goto done;
        }

        for (u32 i = 0; i < num_insts; i++) {
            const u32 raw = read_be32(section->data + i * 4u);
            insts[i] = ppc_decode(raw, section->address + i * 4u);
            if (insts[i].op == PPC_OP_UNKNOWN && embedded_data_word(section->embedded_data_mode, raw))
                insts[i].embedded_data = true;
        }

        int section_ok = 1;
        for (u32 start = 0; section_ok && start < num_insts; start += CHUNK_INSTRUCTIONS) {
            const u32 count = num_insts - start < CHUNK_INSTRUCTIONS ? num_insts - start : CHUNK_INSTRUCTIONS;
            const u32 func_addr = section->address + start * 4u;
            ChunkJob* job = &chunk_jobs[start / CHUNK_INSTRUCTIONS];
            char* name = chunk_names[chunk_count];
            job->insts = insts + start;
            job->count = count;
            job->func_addr = func_addr;
            snprintf(name, 128, "chunk_%04u_%s%u_%08X.c", chunk_count, section->label, section->index,
                     func_addr);
            snprintf(job->include_name, sizeof(job->include_name), HEADER_NAME);
            section_ok = join_path(job->path, sizeof(job->path), chunks_dir, name) &&
                         function_list_add(&funcs, func_addr, func_addr + count * 4u);
            emit_chunk_prototype(header, func_addr);
            chunk_count++;
        }

        // Every chunk entry known so far, so a cross-chunk bl becomes a guarded
        // direct call (see emit_cross_chunk_call). Its index must match the
        // runtime's chunk table, which is sorted by address, so only an
        // ascending chunk list is handed over; a target in a later section is
        // not known yet and keeps the round trip through the runtime.
        u32* chunk_starts = NULL;
        bool ascending = true;
        for (u32 i = 1; i < funcs.count; ++i)
            ascending &= funcs.ranges[i - 1u].start < funcs.ranges[i].start;
        if (section_ok && ascending && funcs.count)
            chunk_starts = (u32*)malloc((size_t)funcs.count * 2u * sizeof(u32));
        if (chunk_starts) {
            for (u32 i = 0; i < funcs.count; ++i) {
                chunk_starts[i] = funcs.ranges[i].start;
                chunk_starts[funcs.count + i] = funcs.ranges[i].end;
            }
            emit_set_chunk_table(chunk_starts, chunk_starts + funcs.count, funcs.count);
        }
        printf("  writing %u chunks with %u jobs\n", job_count, effective_chunk_jobs(job_count, jobs));
        section_ok = section_ok && run_chunk_jobs(chunk_jobs, job_count, jobs);
        emit_set_chunk_table(NULL, NULL, 0);
        free(chunk_starts);
        free(chunk_jobs);
        free(insts);
        if (!section_ok)
            goto done;
    }

    emit_dispatch_helpers(header, &funcs, entry_point);
    emit_footer(header);

    u32* order = (u32*)malloc((section_count ? section_count : 1u) * sizeof(u32));
    if (!order)
        goto done;
    for (u32 i = 0; i < section_count; i++)
        order[i] = i;
    s_sort_sections = sections;
    qsort(order, section_count, sizeof(u32), compare_section_index);
    ok = write_tables(tables_path, sections, section_count, &funcs, order) &&
         write_shards(out_dir, shards, chunk_names, chunk_count);
    free(order);
    if (ok)
        printf("done: %u chunks in %u shards\n", chunk_count, shards);

done:
    if (fclose(header) != 0)
        ok = 0;
    function_list_free(&funcs);
    free(chunk_names);
    return ok;
}

int recompile(const RecompConfig* config, const char* game_dir, const char* out_dir) {
    char dol_path[1200];
    DOLFile dol;
    if (!join_path(dol_path, sizeof(dol_path), game_dir, config->dol) || !dol_load(&dol, dol_path))
        return 0;

    RsoLink rso = {0};
    if (config->sel[0] && !rso_link(&rso, config, game_dir)) {
        dol_free(&dol);
        return 0;
    }

    LoadedCodeSection sections[DOL_NUM_TEXT + 64];
    u32 section_count = 0;
    for (u32 i = 0; i < DOL_NUM_TEXT; i++) {
        const u8* data = dol.header.text_sizes[i] ? dol_get_text_section(&dol, (int)i) : NULL;
        if (!data)
            continue;
        sections[section_count++] = (LoadedCodeSection){
            "text", NULL, data, i, dol.header.text_offsets[i], dol.header.text_addresses[i],
            dol.header.text_sizes[i], EMBEDDED_DATA_DOL};
    }
    // RSO text after the DOL's, numbered on from its sections.
    if (rso.count > sizeof(sections) / sizeof(sections[0]) - section_count) {
        fprintf(stderr, "error: too many RSO text sections\n");
        rso_link_free(&rso);
        dol_free(&dol);
        return 0;
    }
    for (u32 i = 0; i < rso.count; i++) {
        sections[section_count] = (LoadedCodeSection){
            "text", rso.text[i].module, rso.text[i].bytes, section_count, 0, rso.text[i].address,
            rso.text[i].size, EMBEDDED_DATA_DOL};
        section_count++;
    }

    int ok = 0;
    DolRecompNativeList natives = {0};
    u32 entry_count = 0;
    u32* entries = NULL;
    if (config->natives[0]) {
        if (!natives_load(&natives, config->natives) ||
            !natives_verify(&natives, sections, section_count))
            goto done;
        printf("natives: %u guest functions with host implementations\n", natives.count);
        emit_set_natives(natives.entries, natives.count);
    }
    entries = collect_entry_targets(&dol, sections, section_count, &entry_count);
    if (!entries)
        goto done;
    printf("entry targets: %u\n", entry_count);
    emit_set_entry_targets(entries, entry_count);

    ok = emit_sections(sections, section_count, out_dir, dol.header.entry_point, config->shards);

done:
    emit_set_entry_targets(NULL, 0);
    emit_set_natives(NULL, 0);
    free(entries);
    natives_free(&natives);
    rso_link_free(&rso);
    dol_free(&dol);
    return ok;
}
